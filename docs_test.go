// docs/llms.txt is generated: docs/llms.head.md, then docs/reference.md from its first
// "## " heading on, minus the blocks wrapped in skip markers. Edit the sources and run
// `make gen`; this test fails when the committed file differs from the output.

var updateDocs = flag.Bool("update-docs", false, "rewrite docs/llms.txt from its sources (make gen)")

const (
	skipOpen   = "<!-- llms:skip -->"
	skipClose  = "<!-- /llms:skip -->"
	llmsBanner = "<!-- Generated by `make gen` from docs/llms.head.md and docs/reference.md. Do not edit. -->"
)

func splitLines(s string) []string {
	s = strings.ReplaceAll(strings.ReplaceAll(s, "\r\n", "\n"), "\r", "\n")
	return strings.Split(strings.TrimRight(s, "\n"), "\n")
}

type fence struct {
	lang string // first word of the info string, lowercased
	line int    // 1-based line of the opening fence
	body string // the lines between the fences, de-indented by the opening fence's indent
}

var fenceOpenRe = regexp.MustCompile("^([ \t]*)(`{3,}|~{3,})(.*)$")

// scanFences finds the fenced code blocks (``` or ~~~, any indent: fences sit inside
// list items too) and marks every line that belongs to one, fence lines included.
// An unterminated fence is an error: it would swallow the rest of the file.
func scanFences(lines []string) (in []bool, fences []fence, err error) {
	in = make([]bool, len(lines))
	for i := 0; i < len(lines); i++ {
		m := fenceOpenRe.FindStringSubmatch(lines[i])
		if m == nil || m[2][0] == '`' && strings.Contains(m[3], "`") {
			continue
		}
		indent, mark, info := m[1], m[2], strings.TrimSpace(m[3])
		f := fence{line: i + 1}
		if w := strings.Fields(info); len(w) > 0 {
			f.lang = strings.ToLower(w[0])
		}
		closeRe := regexp.MustCompile("^[ \t]*" + regexp.QuoteMeta(mark[:1]) + "{" + fmt.Sprint(len(mark)) + ",}[ \t]*$")
		end := -1
		var body []string
		for j := i + 1; j < len(lines); j++ {
			if closeRe.MatchString(lines[j]) {
				end = j
				break
			}
			body = append(body, strings.TrimPrefix(lines[j], indent))
		}
		if end < 0 {
			return nil, nil, fmt.Errorf("line %d: unterminated code fence", i+1)
		}
		for k := i; k <= end; k++ {
			in[k] = true
		}
		f.body = strings.Join(body, "\n")
		fences = append(fences, f)
		i = end
	}
	return in, fences, nil
}

// dropSkipped removes the skip blocks (and one blank line after each), and fails on any
// marker it does not understand: unbalanced, nested, misspelled. A marker line is the
// whole line (spaces around it are fine); markers inside code fences are literal text.
func dropSkipped(lines []string) ([]string, error) {
	in, _, err := scanFences(lines)
	if err != nil {
		return nil, err
	}
	var out []string
	open := 0 // 1-based line of the open marker, 0 = not in a skip block
	for i := 0; i < len(lines); i++ {
		l := strings.TrimSpace(lines[i])
		// only a line that starts with a comment is a marker: prose may quote one in code
		isMarker := !in[i] && strings.HasPrefix(l, "<!--") && (strings.Contains(l, "llms:") || strings.Contains(l, "/llms:"))
		switch {
		case isMarker && l == skipOpen:
			if open != 0 {
				return nil, fmt.Errorf("line %d: nested %s (open since line %d)", i+1, skipOpen, open)
			}
			open = i + 1
		case isMarker && l == skipClose:
			if open == 0 {
				return nil, fmt.Errorf("line %d: %s without an open %s", i+1, skipClose, skipOpen)
			}
			open = 0
			if i+1 < len(lines) && strings.TrimSpace(lines[i+1]) == "" {
				i++
			}
		case isMarker:
			return nil, fmt.Errorf("line %d: unknown llms marker %q (want %s or %s on a line of its own)", i+1, l, skipOpen, skipClose)
		case open == 0:
			out = append(out, lines[i])
		}
	}
	if open != 0 {
		return nil, fmt.Errorf("line %d: %s is never closed", open, skipOpen)
	}
	return out, nil
}

// genLLMs is the whole generator: banner, head, then the reference body.
func genLLMs(head, ref string) (string, error) {
	if strings.TrimSpace(head) == "" {
		return "", errors.New("llms.head.md is empty")
	}
	hl := splitLines(head)
	if kept, err := dropSkipped(hl); err != nil {
		return "", fmt.Errorf("llms.head.md: %w", err)
	} else if len(kept) != len(hl) {
		return "", errors.New("llms.head.md must not contain skip markers")
	}
	rl, err := dropSkipped(splitLines(ref))
	if err != nil {
		return "", fmt.Errorf("reference.md: %w", err)
	}
	in, _, _ := scanFences(rl) // balanced: dropSkipped scanned the same lines
	first := -1
	for i, l := range rl {
		if !in[i] && strings.HasPrefix(l, "## ") {
			first = i
			break
		}
	}
	if first < 0 {
		return "", errors.New(`reference.md has no "## " heading`)
	}
	body := rl[first:]
	out := llmsBanner + "\n" + strings.Join(hl, "\n") + "\n\n" + strings.TrimRight(strings.Join(body, "\n"), "\n ") + "\n"
	if _, _, err := scanFences(splitLines(out)); err != nil {
		return "", fmt.Errorf("generated output: %w", err)
	}
	return out, nil
}

// syncLLMs regenerates root/docs/llms.txt from its sources: with update it writes the
// file, otherwise it reports a stale one.
func syncLLMs(root string, update bool) error {
	read := func(name string) (string, error) {
		b, err := os.ReadFile(filepath.Join(root, "docs", name))
		return string(b), err
	}
	head, err := read("llms.head.md")
	if err != nil {
		return err
	}
	ref, err := read("reference.md")
	if err != nil {
		return err
	}
	want, err := genLLMs(head, ref)
	if err != nil {
		return err
	}
	got, _ := read("llms.txt") // missing = stale
	if got == want {
		return nil
	}
	if update {
		return os.WriteFile(filepath.Join(root, "docs", "llms.txt"), []byte(want), 0o644)
	}
	gl, wl := strings.Split(got, "\n"), strings.Split(want, "\n")
	n := 0
	for n < len(gl) && n < len(wl) && gl[n] == wl[n] {
		n++
	}
	return fmt.Errorf("docs/llms.txt is stale: run make gen (edit docs/llms.head.md or docs/reference.md, never docs/llms.txt); first difference at line %d", n+1)
}

func TestLLMsTxtIsFresh(t *testing.T) {
	if err := syncLLMs(".", *updateDocs); err != nil {
		t.Fatal(err)
	}
}

var (
	codeSpanRe = regexp.MustCompile("`[^`]*`")
	linkRe     = regexp.MustCompile(`\]\(([^)\s]+)`)
)

// headingSlug is GitHub's anchor for a heading: lowercase, punctuation dropped, spaces as hyphens.
func headingSlug(h string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(strings.TrimSpace(h)) {
		switch {
		case r == ' ':
			b.WriteByte('-')
		case r == '-' || r == '_' || unicode.IsLetter(r) || unicode.IsDigit(r):
			b.WriteRune(r)
		}
	}
	return b.String()
}

// The generated file is served alone from GitHub Pages, so it must not hold markers,
// lose the core reference sections, or link to a path that only exists in the repo.
func TestLLMsTxtShape(t *testing.T) {
	b, err := os.ReadFile("docs/llms.txt")
	if err != nil {
		t.Fatal(err)
	}
	txt := string(b)
	if strings.Contains(txt, "<!-- llms:") || strings.Contains(txt, "<!-- /llms:") {
		t.Error("a skip marker leaked into llms.txt")
	}
	if strings.Contains(txt, "\r") || !strings.HasSuffix(txt, "\n") || strings.HasSuffix(txt, "\n\n") {
		t.Error("llms.txt must use LF and end with exactly one newline")
	}
	if !strings.HasPrefix(txt, llmsBanner+"\n") {
		t.Error("llms.txt must start with the generated banner")
	}
	for _, h := range []string{"## Integration recipe", "## Rules", "## Troubleshooting", "## Config", "## API", "### Events", "## How it behaves", "## Not in v1"} {
		if !strings.Contains(txt, "\n"+h+"\n") {
			t.Errorf("llms.txt lost the %q section", h)
		}
	}
	for _, h := range []string{"## Quick start", "## Development", "### Conventions"} {
		if strings.Contains(txt, "\n"+h+"\n") {
			t.Errorf("llms.txt still has the maintainer section %q", h)
		}
	}
	lines := splitLines(txt)
	in, _, _ := scanFences(lines)
	anchors := map[string]bool{}
	for i, l := range lines {
		if !in[i] && strings.HasPrefix(l, "#") {
			anchors[headingSlug(strings.TrimLeft(l, "# "))] = true
		}
	}
	for i, l := range lines {
		if in[i] {
			continue
		}
		for _, m := range linkRe.FindAllStringSubmatch(codeSpanRe.ReplaceAllString(l, ""), -1) {
			if a, ok := strings.CutPrefix(m[1], "#"); ok && !anchors[a] {
				t.Errorf("line %d: link to #%s, but no such heading is left in llms.txt (a skipped section?)", i+1, a)
			}
		}
		for _, m := range linkRe.FindAllStringSubmatch(codeSpanRe.ReplaceAllString(l, ""), -1) {
			if target := m[1]; !strings.HasPrefix(target, "http") && !strings.HasPrefix(target, "#") {
				t.Errorf("line %d: relative link %q breaks when llms.txt is served from Pages", i+1, target)
			}
		}
	}
}

func TestGenLLMs(t *testing.T) {
	const head = "# hfy\n\nhead text\n"
	body := func(parts ...string) string { return "# ref\n\npreamble\n\n" + strings.Join(parts, "") }
	cases := []struct {
		name, head, ref string
		want            string // exact output; "" with wantErr set
		wantErr         string
	}{
		{name: "preamble dropped, body verbatim", head: head, ref: body("## A\n\ntext\n\n### B\n\nmore\n"),
			want: llmsBanner + "\n# hfy\n\nhead text\n\n## A\n\ntext\n\n### B\n\nmore\n"},
		{name: "skip block and one blank line after it", head: head,
			ref:  body("## A\n\none\n\n<!-- llms:skip -->\n## Dev\n\nsecret\n<!-- /llms:skip -->\n\n## C\n\ntwo\n"),
			want: llmsBanner + "\n# hfy\n\nhead text\n\n## A\n\none\n\n## C\n\ntwo\n"},
		{name: "skip block first in the body", head: head,
			ref:  body("<!-- llms:skip -->\n## Quick\n<!-- /llms:skip -->\n\n## A\n\none\n"),
			want: llmsBanner + "\n# hfy\n\nhead text\n\n## A\n\none\n"},
		{name: "skip block up to the end", head: head,
			ref:  body("## A\n\none\n\n<!-- llms:skip -->\n## Dev\n\nx\n<!-- /llms:skip -->\n"),
			want: llmsBanner + "\n# hfy\n\nhead text\n\n## A\n\none\n"},
		{name: "marker with spaces around it", head: head,
			ref:  body("## A\n  <!-- llms:skip -->  \nx\n\t<!-- /llms:skip -->\t\n## B\n"),
			want: llmsBanner + "\n# hfy\n\nhead text\n\n## A\n## B\n"},
		{name: "CRLF and missing final newline", head: "# hfy\r\n\r\nhead text", ref: "# ref\r\n\r\n## A\r\n\r\ntext",
			want: llmsBanner + "\n# hfy\n\nhead text\n\n## A\n\ntext\n"},
		{name: "marker inside a code fence is literal", head: head,
			ref:  body("## A\n\n```md\n<!-- llms:skip -->\n```\n\ntext\n"),
			want: llmsBanner + "\n# hfy\n\nhead text\n\n## A\n\n```md\n<!-- llms:skip -->\n```\n\ntext\n"},
		{name: "marker quoted in prose or code spans is not a marker", head: head + "Wrap it in `<!-- llms:skip -->` and `<!-- /llms:skip -->`.\n",
			ref:  body("## A\n\nUse `<!-- llms:skip -->` to skip. Text <!-- llms:skip --> mid-line.\n\n- `<!-- /llms:skip -->` ends it\n"),
			want: llmsBanner + "\n# hfy\n\nhead text\nWrap it in `<!-- llms:skip -->` and `<!-- /llms:skip -->`.\n\n## A\n\nUse `<!-- llms:skip -->` to skip. Text <!-- llms:skip --> mid-line.\n\n- `<!-- /llms:skip -->` ends it\n"},
		{name: "other html comments are left alone", head: head, ref: body("## A\n<!-- note -->\ntext\n"),
			want: llmsBanner + "\n# hfy\n\nhead text\n\n## A\n<!-- note -->\ntext\n"},
		{name: "## inside a fence is not the first heading", head: head,
			ref:  "# ref\n\n```md\n## not a heading\n```\n\n## Real\n",
			want: llmsBanner + "\n# hfy\n\nhead text\n\n## Real\n"},

		{name: "nested skip", head: head, ref: body("## A\n<!-- llms:skip -->\n<!-- llms:skip -->\n<!-- /llms:skip -->\n<!-- /llms:skip -->\n"), wantErr: "nested"},
		{name: "unterminated skip", head: head, ref: body("## A\n<!-- llms:skip -->\nx\n"), wantErr: "never closed"},
		{name: "close before open", head: head, ref: body("## A\n<!-- /llms:skip -->\n<!-- llms:skip -->\n"), wantErr: "without an open"},
		{name: "misspelled marker", head: head, ref: body("## A\n<!-- llms:skp -->\n"), wantErr: "unknown llms marker"},
		{name: "marker with trailing text", head: head, ref: body("## A\n<!-- llms:skip --> why\n"), wantErr: "unknown llms marker"},
		{name: "no heading", head: head, ref: "# ref\n\ntext\n", wantErr: `no "## " heading`},
		{name: "empty head", head: " \n\n", ref: body("## A\n"), wantErr: "empty"},
		{name: "marker in head", head: head + "<!-- llms:skip -->\nx\n<!-- /llms:skip -->\n", ref: body("## A\n"), wantErr: "must not contain skip markers"},
		{name: "unterminated fence in reference", head: head, ref: body("## A\n\n```yaml\nx: 1\n"), wantErr: "unterminated"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got, err := genLLMs(c.head, c.ref)
			if c.wantErr != "" {
				if err == nil || !strings.Contains(err.Error(), c.wantErr) {
					t.Fatalf("err = %v, want one containing %q", err, c.wantErr)
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			if got != c.want {
				t.Fatalf("got:\n%q\nwant:\n%q", got, c.want)
			}
			if again, _ := genLLMs(c.head, c.ref); again != got {
				t.Fatal("output is not deterministic")
			}
		})
	}
}

func TestScanFences(t *testing.T) {
	cases := []struct {
		name, md string
		langs    []string // lang of each fence found
		bodies   []string
		wantErr  bool
	}{
		{name: "plain", md: "a\n```yaml\nx: 1\n```\nb", langs: []string{"yaml"}, bodies: []string{"x: 1"}},
		{name: "no language", md: "```\nx\n```", langs: []string{""}, bodies: []string{"x"}},
		{name: "tilde fence", md: "~~~yaml\nx: 1\n~~~", langs: []string{"yaml"}, bodies: []string{"x: 1"}},
		{name: "four backticks hold three", md: "````md\n```yaml\nx: 1\n```\n````", langs: []string{"md"}, bodies: []string{"```yaml\nx: 1\n```"}},
		{name: "a shorter fence does not close", md: "````\n```\n````", langs: []string{""}, bodies: []string{"```"}},
		{name: "a different mark does not close", md: "```\n~~~\n```", langs: []string{""}, bodies: []string{"~~~"}},
		{name: "indented in a list, body de-indented", md: "- item\n\n  ```yaml\n  a:\n    b: 1\n  ```\n- next", langs: []string{"yaml"}, bodies: []string{"a:\n  b: 1"}},
		{name: "language case and extra info", md: "```YAML title=x\na: 1\n```", langs: []string{"yaml"}, bodies: []string{"a: 1"}},
		{name: "inline triple backticks are not a fence", md: "use ```code``` here\n", langs: nil},
		{name: "two fences", md: "```sh\na\n```\n\n```yml\nb: 1\n```", langs: []string{"sh", "yml"}, bodies: []string{"a", "b: 1"}},
		{name: "closing fence may carry spaces", md: "```yaml\na: 1\n```  \n", langs: []string{"yaml"}, bodies: []string{"a: 1"}},
		{name: "unterminated", md: "text\n```yaml\na: 1\n", wantErr: true},
		{name: "shorter close is unterminated", md: "````yaml\na: 1\n```\n", wantErr: true},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			_, fs, err := scanFences(splitLines(c.md))
			if (err != nil) != c.wantErr {
				t.Fatalf("err = %v, wantErr %v", err, c.wantErr)
			}
			var langs, bodies []string
			for _, f := range fs {
				langs, bodies = append(langs, f.lang), append(bodies, f.body)
			}
			if strings.Join(langs, "|") != strings.Join(c.langs, "|") || (c.bodies != nil && strings.Join(bodies, "|") != strings.Join(c.bodies, "|")) {
				t.Fatalf("langs %q bodies %q; want %q %q", langs, bodies, c.langs, c.bodies)
			}
		})
	}
}

// A copy of the sources in a temp dir: a hand-edited llms.txt, an edited source, and a
// missing file are all reported as stale; -update-docs repairs them.
func TestLLMsStaleIsDetected(t *testing.T) {
	root := t.TempDir()
	must := func(err error) {
		t.Helper()
		if err != nil {
			t.Fatal(err)
		}
	}
	must(os.MkdirAll(filepath.Join(root, "docs"), 0o755))
	write := func(name, s string) { must(os.WriteFile(filepath.Join(root, "docs", name), []byte(s), 0o644)) }
	write("llms.head.md", "# hfy\n\nhead\n")
	write("reference.md", "# ref\n\n## A\n\ntext\n")

	stale := func() error {
		t.Helper()
		err := syncLLMs(root, false)
		if err == nil || !strings.Contains(err.Error(), "docs/llms.txt is stale: run make gen") {
			t.Fatalf("err = %v, want the stale message", err)
		}
		return err
	}
	stale() // missing
	must(syncLLMs(root, true))
	must(syncLLMs(root, false))

	b, err := os.ReadFile(filepath.Join(root, "docs", "llms.txt"))
	must(err)
	write("llms.txt", string(b)+"hand edit\n")
	stale()
	must(syncLLMs(root, true))
	must(syncLLMs(root, false))

	write("reference.md", "# ref\n\n## A\n\nchanged\n")
	if err := stale(); !strings.Contains(err.Error(), "line 8") {
		t.Fatalf("the message should name the first differing line: %v", err)
	}

	write("reference.md", "# ref\n\n## A\n<!-- llms:skip -->\n") // a bad source is an error, never a stale file
	if err := syncLLMs(root, true); err == nil || strings.Contains(err.Error(), "stale") {
		t.Fatalf("err = %v, want a marker error", err)
	}
}
